const DRAGON_AGES = { young: ["Jovem", "joven"], adult: ["Adulto", "adulto"], ancient: ["Ancião", "anciano"] };

/** Dragões cromáticos e metálicos: "Dragão Vermelho Jovem", "Filhote de Dragão Vermelho". */
function dragon(pk) {
  let m = /^(young|adult|ancient)-(\w+)-dragon$/.exec(pk);
  if (m && DRAGON_COLORS[m[2]]) {
    const [cp, ce] = DRAGON_COLORS[m[2]];
    const [ap, ae] = DRAGON_AGES[m[1]];
    return [`Dragão ${cp} ${ap}`, `Dragón ${ce} ${ae}`];
  }
  m = /^(\w+)-dragon-wyrmling$/.exec(pk);
  if (m && DRAGON_COLORS[m[1]]) {
    const [cp, ce] = DRAGON_COLORS[m[1]];
    return [`Filhote de Dragão ${cp}`, `Cría de dragón ${ce}`];
  }
  return null;
}

